package site.albaniacraft.towns.web

import site.albaniacraft.towns.TownManager
import java.io.InputStreamReader
import java.nio.charset.StandardCharsets
import javax.servlet.http.HttpServlet
import javax.servlet.http.HttpServletRequest
import javax.servlet.http.HttpServletResponse


class StatisticsServlet(private val townManager: TownManager) : HttpServlet() {
    override fun doGet(request: HttpServletRequest, response: HttpServletResponse) {
        response.contentType = "text/html;charset=utf-8"
        response.status = HttpServletResponse.SC_OK

        // Read the content of index.html from resources
        val indexPath = "/web/index.html"  // Note the leading slash
        val htmlStream = javaClass.getResourceAsStream(indexPath)
        val htmlContent = htmlStream?.let { InputStreamReader(it, StandardCharsets.UTF_8).use { it.readText() } }

        // Inject dynamic content into the HTML
        val towns = townManager.getAllTowns()
        val dynamicContent = buildHtmlContent(towns)
        val finalHtmlContent = htmlContent?.replace("<!-- The content here will be dynamically generated by the servlet -->", dynamicContent)

        response.writer.println(finalHtmlContent)
    }
    private fun buildHtmlContent(towns: List<String>): String {
        val sb = StringBuilder()

        for (townName in towns) {
            val town = townManager.getTown(townName)
            sb.append("<li>")
            sb.append("Town Name: ${town.name}<br>")
            sb.append("Mayor: ${town.founder}<br>")
            sb.append("Claimed Chunks: ${townManager.getClaimedChunksCount(townName)}<br>")
            sb.append("Members: ${town.members.joinToString(", ")}<br>")
            sb.append("Balance: ${townManager.getTownBalance(townName)}<br>")
            sb.append("</li>")
        }
        return sb.toString()
    }
}
